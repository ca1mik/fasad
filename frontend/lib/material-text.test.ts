import { describe, expect, it } from "vitest";

import { cleanColorText, thicknessFromText } from "@/lib/material-text";

/**
 * Разбор колонки «Цвет» из бланка заказчика.
 *
 * Браузером эти ошибки не ловятся: на экране «003» в графе толщины выглядит
 * ровно так же правдоподобно, как «19», а карты раскроя разъезжаются молча.
 * Поэтому правило проверяем числами, а не глазами.
 */
describe("толщина внутри текста цвета", () => {
  it("достаёт толщину, написанную рядом с цветом", () => {
    // В бланке студии колонка «Мм» часто пустая, а толщина указана в цвете.
    expect(thicknessFromText("Эмаль RAL 9003 плита 19мм")).toBe("19");
    expect(thicknessFromText("ПВХ Белый глянец 16 мм")).toBe("16");
    expect(thicknessFromText("плита 19,5 мм дуб")).toBe("19.5");
  });

  it("не принимает хвост номера RAL за миллиметры", () => {
    // Ради этого случая правило и написано: «RAL 9003мм» — это номер цвета,
    // а не 003 миллиметра. Ошибка тихая: деталь уехала бы на карту 3 мм.
    expect(thicknessFromText("RAL 9003мм")).toBeNull();
  });

  it("не выдумывает толщину там, где её нет", () => {
    expect(thicknessFromText("Тадж Прага P833UP")).toBeNull();
    expect(thicknessFromText("")).toBeNull();
    expect(thicknessFromText(null)).toBeNull();
  });

  it("отбрасывает значения вне разумных пределов плиты", () => {
    // «300 мм» в графе толщины — это не плита, а чей-то размер.
    expect(thicknessFromText("плита 300мм")).toBeNull();
  });
});

describe("цвет из бланка — только цвет", () => {
  it("сводит запись с RAL к каноничной", () => {
    expect(cleanColorText("Эмаль RAL 9003 плита 19мм")).toBe("RAL 9003");
    expect(cleanColorText("эмаль рал-9003")).toBe("RAL 9003");
  });

  it("срезает вид работ и толщину, оставляя название декора", () => {
    expect(cleanColorText("ПВХ Белый глянец 16 мм")).toBe("Белый глянец");
  });

  it("не режет название декора, где значим каждый символ", () => {
    expect(cleanColorText("Тадж Прага P833UP")).toBe("Тадж Прага P833UP");
  });

  it("возвращает исходную запись, если кроме вида работ в ней ничего нет", () => {
    // Пустая ячейка хуже: менеджер решит, что цвет потеряли.
    expect(cleanColorText("мдф 16мм")).toBe("мдф 16мм");
  });

  it("не падает на пустом значении", () => {
    expect(cleanColorText(null)).toBe("");
    expect(cleanColorText("   ")).toBe("");
  });
});
