/**
 * Цвет из бланка заказчика — только цвет.
 *
 * В колонке «Цвет» студия пишет строкой всё сразу: вид работ, основу и
 * толщину — «Эмаль RAL 9003 плита 19мм». Для человека это одна запись, но в
 * системе это три разных поля: толщина живёт в своей графе и делит карты
 * раскроя, вид работ — это артикул из справочника, а цветом остаётся только
 * цвет. Пока лишнее оставалось в строке, на карте раскроя стояла подпись
 * «Эмаль RAL 9003 плита 19мм · ФР-02», и в цехе её читали как название
 * материала целиком.
 *
 * Чистим только на показе: в базе исходная запись остаётся нетронутой —
 * менеджеру нужно сверять её с бумагой.
 */

/**
 * «RAL 9003», «RAL9003», «рал-9003» — заказчик пишет по-разному.
 *
 * Слева граница проверяется своей группой, а не `\b`: в JavaScript граница
 * слова считается только по латинице, поэтому перед кириллическим «рал» она не
 * срабатывает никогда — и запись «эмаль рал-9003» к каноничной не сводилась.
 * В списке цветов «Рал-9003» и «RAL 9003» оказывались разными значениями, хотя
 * это один цвет.
 */
const RAL_PATTERN = /(^|[^A-Za-zА-Яа-яЁё])(?:RAL|РАЛ)\s*-?\s*(\d{3,4})\b/i;

/**
 * Толщина внутри текста: «плита 19мм», «16 мм», «19,5 мм».
 *
 * Предыдущий знак захватываем группой и проверяем сами — без этого из
 * «RAL 9003мм» вырезалось бы «003». Взгляд назад (`(?<!…)`) сделал бы то же
 * короче, но его не понимают браузеры до Safari 16.4: там модуль не
 * компилируется вовсе, и вместе с ним падает вся форма заявки и таблица сметы,
 * а не только разбор толщины. Заявки заносят и с планшета в цехе, поэтому здесь
 * то же правило, что в `lib/cutting-layout.ts`, — там от взгляда назад
 * отказались по этой же причине.
 *
 * Справа стоит `(?![а-яё])`, а не `\b`: граница слова в JavaScript считается
 * только по латинице, поэтому после кириллического «мм» она не срабатывает
 * никогда и правило молча переставало находить толщину.
 */
const THICKNESS_PATTERN = /(^|[^\d.,])(\d{1,3}(?:[.,]\d+)?\s*мм)(?![а-яё])/gi;

/**
 * Основа и вид работ. Это не цвет: на чём делают — отдельное поле, а вид
 * работ приходит артикулом из справочника.
 */
const KIND_WORDS = [
  "эмаль",
  "эмалевый",
  "эмалированный",
  "пвх",
  "pvc",
  "плёнка",
  "пленка",
  "плита",
  "мдф",
  "mdf",
  "лдсп",
  "хдф",
  "дсп",
  "шпон",
  "шпонированный",
  "массив",
  "акрил",
  "пластик",
];

const KIND_PATTERN = new RegExp(`(?:^|\\s)(?:${KIND_WORDS.join("|")})(?=\\s|$)`, "gi");

/** Мусор, остающийся на стыках после вырезания слов: «·», «,», «-» подряд. */
const LEFTOVER_SEPARATORS = /^[\s,;·—–-]+|[\s,;·—–-]+$/g;

function collapseSpaces(value: string) {
  return value.replace(/\s+/g, " ").trim();
}

/** Разумные пределы толщины плиты: всё вне их — не толщина, а случайное число. */
const MIN_THICKNESS_MM = 1;
const MAX_THICKNESS_MM = 100;

/**
 * Толщина, написанная внутри текста цвета: «Эмаль RAL 9003 плита 19мм» → «19».
 *
 * В бланке заказчика колонка «Мм» часто пустая, а толщина указана прямо в
 * цвете. Достаём её оттуда, пока текст не вычищен: на распиле толщина делит
 * карты, и потерять её нельзя.
 */
export function thicknessFromText(value: string | null | undefined): string | null {
  const text = collapseSpaces(String(value ?? ""));
  if (!text) {
    return null;
  }

  THICKNESS_PATTERN.lastIndex = 0;
  for (const match of text.matchAll(THICKNESS_PATTERN)) {
    // match[1] — захваченный предыдущий знак, сама толщина во второй группе.
    const digits = match[2].replace(/\s*мм$/i, "").replace(",", ".");
    const number = Number(digits);
    if (Number.isFinite(number) && number >= MIN_THICKNESS_MM && number <= MAX_THICKNESS_MM) {
      // «19.0» → «19»: в заказ идёт число, а не запись из ячейки
      return String(number);
    }
  }
  return null;
}

/**
 * Цвет в том виде, в каком его нужно показывать.
 *
 * Есть RAL — от записи остаётся каноничное «RAL 9003», всё остальное к цвету
 * отношения не имеет. Нет RAL — вырезаем толщину и основу, а название декора
 * оставляем целиком: «Тадж Прага P833UP» резать нельзя, там значим каждый
 * символ.
 *
 * Если после чистки не осталось ничего — значит в строке был только вид
 * работ, и показать лучше исходную запись, чем пустую ячейку.
 */
export function cleanColorText(value: string | null | undefined): string {
  const text = collapseSpaces(String(value ?? ""));
  if (!text) {
    return "";
  }

  const ral = RAL_PATTERN.exec(text);
  if (ral) {
    // Номер во второй группе: первая — захваченный знак перед «RAL».
    return `RAL ${ral[2]}`;
  }

  const stripped = collapseSpaces(
    // Предыдущий знак захвачен группой, поэтому возвращаем его на место —
    // иначе «плита 19мм» съело бы и пробел перед числом вместе с буквой «а».
    text.replace(THICKNESS_PATTERN, (_match, before: string) => `${before} `)
      .replace(KIND_PATTERN, " "),
  ).replace(LEFTOVER_SEPARATORS, "");

  if (!stripped) {
    return text;
  }

  // Заглавная буква возвращается, только если её срезали вместе с видом
  // работ: «ПВХ Белый глянец» → «Белый глянец», а «дуб натуральный» из
  // справочника остаётся как записан.
  if (stripped[0] !== text[0] && /[а-яa-z]/.test(stripped[0])) {
    return stripped[0].toUpperCase() + stripped.slice(1);
  }
  return stripped;
}

/**
 * Номер артикула без приставки, как его хранит справочник.
 *
 * Повторяет правило сервера (`PriceBookService._normalize_article`): «Арт 109»,
 * «артикул 109» и «109» — один и тот же артикул. Нужен, чтобы набранный номер
 * находил позицию прайса: подпись в поиске выглядит как «109 · Фрезеровка», и
 * по ней голый номер не совпадал ни с чем.
 */
export function articleKey(value: string | null | undefined): string {
  const text = collapseSpaces(String(value ?? ""));
  if (!text) {
    return "";
  }
  const cleaned = text.replace(/^(?:артикул|арт|article|art)[.\s№]*(?=\d)/i, "");
  const parts = cleaned.split(" ").filter(Boolean);
  // Составной номер вроде «ФР 01» остаётся целым, словесный хвост отбрасываем.
  if (parts.length > 1 && !parts.slice(1).some((word) => /\d/.test(word))) {
    return parts[0].toUpperCase();
  }
  return cleaned.toUpperCase();
}

// articleFromText убрана: переносить номер из «Фрезеровки» в отдельную графу
// «Артикул» было нужно, пока это были две разные графы. Теперь это одна
// графа (и в таблице заявки, и в смете заказа) — переносить уже нечего.
